function line(mark, r, dept) {
  return mark + ' ' + r.total.toFixed(1) + '/5  ' + dept
    + '   ' + r.axes.map(function (a) { return a.smart + (a.score === null ? '-' : a.score); }).join(' ');
}

let failed = 0;
console.log('■ よく書けている目標（4.0点以上が期待値）');
console.log('');

goodDrafts.forEach(function (c) {
  const r = scoreDraft(c.text);
  const weak = r.axes.filter(function (a) { return a.score !== null && a.score <= 2; });
  console.log(line(r.total >= 4.0 ? '  OK ' : '  低い', r, c.dept));
  if (weak.length > 0) {
    console.log('        弱い観点  : ' + weak.map(function (a) { return a.label; }).join('・'));
    console.log('        拾えた数量: ' + (r.detected.quantities.join('／') || 'なし'));
    console.log('        拾えた行動: ' + (r.detected.actions.join('／') || 'なし'));
  }
  if (r.total < 4.0) failed++;
});

console.log('');
console.log(failed === 0
  ? 'すべて4.0点以上。語彙の穴は見つかりませんでした。'
  : failed + ' 件が4.0点未満。上の「弱い観点」を手がかりに語彙を補うこと。');

console.log('');
console.log('■ 弱い目標（2.5点以下が期待値。語彙を広げすぎていないかの確認）');
console.log('');

let tooKind = 0;
weakDrafts.forEach(function (c) {
  const r = scoreDraft(c.text);
  console.log(line(r.total <= 2.5 ? '  OK ' : '  甘い', r, c.dept));
  if (r.total > 2.5) tooKind++;
});

console.log('');
console.log(tooKind === 0
  ? '弱い目標はきちんと低く出ています。'
  : tooKind + ' 件が甘く出ています。語彙を広げすぎていないか見直すこと。');

process.exit(failed === 0 && tooKind === 0 ? 0 : 1);
